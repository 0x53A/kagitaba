"""Independent format vectors: uv run tests/reference_vectors.py.

Uses PyCA/OpenSSL for P-256 and libsodium for XChaCha20-Poly1305, not the
RustCrypto implementations linked into Kagitaba. Only public test secrets.
The output is tests/fixtures/reference.rs; this script does not write files.
"""

import hashlib
import hmac

from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat
from nacl.bindings import crypto_aead_xchacha20poly1305_ietf_encrypt


def sha256(data: bytes) -> bytes:
    return hashlib.sha256(data).digest()


def literal(name: str, data: bytes) -> None:
    print(f'pub const {name}: &str = "{data.hex()}";')


recipient = ec.derive_private_key(1, ec.SECP256R1())
ephemeral = ec.derive_private_key(2, ec.SECP256R1())
recipient_der = recipient.public_key().public_bytes(Encoding.DER, PublicFormat.SubjectPublicKeyInfo)
recipient_point = recipient.public_key().public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)
ephemeral_point = ephemeral.public_key().public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)
key = bytes([0x42]) * 32
nonce = bytes(range(24))
context = b"independent Kagitaba format vector"
plaintext = b"a public test password\x00\xff"

payload_header = b"KTC1" + nonce + sha256(context)
payload = payload_header + crypto_aead_xchacha20poly1305_ietf_encrypt(plaintext, payload_header, nonce, key)

grant_header = b"KTW1" + sha256(recipient_der) + sha256(context) + ephemeral_point + nonce
shared = ephemeral.exchange(ec.ECDH(), recipient.public_key())
salt = sha256(b"Kagitaba/v1/ecdh-salt\x00" + ephemeral_point + recipient_point)
# RFC 5869 extract and a single expand block (32-byte output).
prk = hmac.digest(salt, shared, "sha256")
wrapping_key = hmac.digest(prk, b"Kagitaba/v1/wrapping-key\x00" + grant_header + b"\x01", "sha256")
grant = grant_header + crypto_aead_xchacha20poly1305_ietf_encrypt(key, grant_header, nonce, wrapping_key)

print("// Generated by tests/reference_vectors.py using independent crypto implementations.")
literal("PUBLIC_DER", recipient_der)
literal("CONTEXT", context)
literal("PLAINTEXT", plaintext)
literal("PAYLOAD", payload)
literal("GRANT", grant)
